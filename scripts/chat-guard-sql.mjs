// Prints one SQL query that proves the Postgres guard and the browser guard
// agree, message for message.
//
// It does not restate the expected answers — it runs the browser copy here,
// embeds what it actually decided, and asks Postgres whether it decided the
// same. Any row returned is a disagreement between the two copies, which is
// the only bug that matters: the browser warns, the database enforces, and a
// person who is warned about one thing and blocked for another stops trusting
// either.
//
// Usage: node scripts/chat-guard-sql.mjs | psql …    (no rows = in step)
import { readFileSync } from 'node:fs';
await import('../cabana-chat-guard.js');
const Guard = globalThis.CabanaChatGuard;

const v = JSON.parse(readFileSync(new URL('../tests/chat-guard.vectors.json', import.meta.url), 'utf8'));
const q = s => "'" + String(s).replace(/'/g, "''") + "'";
const cats = r => [...r.hard].sort().join(',');

const single = v.single.map(x => `(${q(x.text)}, ${q(cats(Guard.check(x.text)))})`).join(',\n  ');

const anc = Guard.anchorTokens(v.anchored.anchors);
const anchored = v.anchored.cases.map(x => {
  const r = Guard.check(x.text, { anchors: anc, contactAllowed: !!x.contactAllowed });
  return `(${q(x.text)}, ${q(cats(r))}, ${!!x.contactAllowed})`;
}).join(',\n  ');

const seq = v.sequences.map(s => {
  const prev = s.messages.slice(0, -1), last = s.messages.at(-1);
  return `(array[${prev.map(q).join(',')}]::text[], ${q(last)}, ${Guard.spansMessages(prev, last)})`;
}).join(',\n  ');

console.log(`-- Generated by scripts/chat-guard-sql.mjs from cabana-chat-guard.js v${Guard.version}.
-- Each row carries what the BROWSER decided. Postgres re-decides and disagreements surface.
with anc as (select cabana_private.guard_anchor_tokens(array[${v.anchored.anchors.map(q).join(',')}]::text[]) a)
select 'single' as scope, t as message, js as browser, coalesce(pg, '') as postgres
from (values
  ${single}
) s(t, js), lateral (select (select string_agg(x, ',' order by x)
  from jsonb_array_elements_text(cabana_private.chat_guard(t)->'hard') x) pg) p
where coalesce(pg, '') is distinct from js

union all
select 'anchored', t, js, coalesce(pg, '')
from (values
  ${anchored}
) s(t, js, ca), anc, lateral (select (select string_agg(x, ',' order by x)
  from jsonb_array_elements_text(cabana_private.chat_guard(t, ca, anc.a)->'hard') x) pg) p
where coalesce(pg, '') is distinct from js

union all
select 'sequence', p::text || ' + ' || t, js::text, cabana_private.chat_guard_spans(p, t)::text
from (values
  ${seq}
) s(p, t, js)
where cabana_private.chat_guard_spans(p, t) is distinct from js;`);
