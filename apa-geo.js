  /* ── Reverse ──────────────────────────────────────────────────── */

  function reverse(lat, lng) {
    lat = Number(lat); lng = Number(lng);
    if (!isFinite(lat) || !isFinite(lng)) return Promise.resolve(null);

    var key = 'gr:' + lat.toFixed(4) + ',' + lng.toFixed(4);
    if (mem[key]) return Promise.resolve(mem[key]);
    var stored = ssGet(key);
    if (stored) { mem[key] = stored; return Promise.resolve(stored); }

    var u = apiAlive
      ? API + '?lat=' + lat + '&lng=' + lng + '&lang=' + docLang()
      : 'https://photon.komoot.io/reverse?lat=' + lat + '&lon=' + lng + '&lang=en';

    return fetch(u)
      .then(function (r) {
        if (r.status === 404) { apiAlive = false; throw new Error('no route'); }
        return r.ok ? r.json() : null;
      })
      .then(function (d) {
        if (!d) return null;
        var row = d.results ? d.results[0] : (d.features || [])[0];
        if (!row) return null;
        var p = d.results ? place(row) : fromPhoton(row);
        if (p) { mem[key] = p; ssSet(key, p); }
        return p;
      })
      .catch(function () {
        /* A pin without a label is still a pin. Callers treat the label
           as decoration precisely so this can fail quietly. */
        return null;
      });
  }

  /* ── The device's own fix ─────────────────────────────────────── */

  function locate(o) {
    o = o || {};
    return new Promise(function (res, rej) {
      if (!navigator.geolocation) return rej(new Error('This device cannot share a location'));
      navigator.geolocation.getCurrentPosition(function (pos) {
        var lat = pos.coords.latitude, lng = pos.coords.longitude;
        reverse(lat, lng).then(function (p) {
          var out = p || place({ name: 'Current location', lat: lat, lng: lng, kind: 'poi', source: 'device' });
          /* Keep the true fix. The reverse geocode names the street; it
             must not move the point to the middle of it. */
          out.lat = lat; out.lng = lng;
          out.accuracy = pos.coords.accuracy || null;
          out.source = 'device';
          setBias(out);
          res(out);
        });
      }, function (err) {
        rej(new Error(
          err.code === 1 ? 'Location permission was declined — type the place instead'
                         : 'Could not read your location — type the place instead'
        ));
      }, {
        enableHighAccuracy: o.highAccuracy !== false,
        timeout: o.timeout || 12000,
        maximumAge: o.maximumAge != null ? o.maximumAge : 60000
      });
    });
  }

  /* ════════════════════════════════════════════════════════════════
     5 · GEOMETRY

     What makes a search a search rather than a string comparison.
     ════════════════════════════════════════════════════════════════ */

  function distance(a, b) {
    if (!a || !b) return Infinity;
    var lat1 = Number(a.lat), lng1 = Number(a.lng), lat2 = Number(b.lat), lng2 = Number(b.lng);
    if (!isFinite(lat1) || !isFinite(lng1) || !isFinite(lat2) || !isFinite(lng2)) return Infinity;
    var R = 6371, p = Math.PI / 180;
    var dLat = (lat2 - lat1) * p, dLng = (lng2 - lng1) * p;
    var s = Math.sin(dLat / 2) * Math.sin(dLat / 2) +
            Math.cos(lat1 * p) * Math.cos(lat2 * p) * Math.sin(dLng / 2) * Math.sin(dLng / 2);
    return 2 * R * Math.atan2(Math.sqrt(s), Math.sqrt(1 - s));
  }

  /* A sensible first radius for what was searched. Someone who typed a
     street means the street; someone who typed a country means the
     country, and offering them a 5km circle around its centroid would
     be absurd. */
  function radiusFor(p, fallback) {
    if (!p) return fallback || 25;
    if (p.bbox) {
      /* Half the diagonal of the place's own extent is the honest
         radius — it is the geocoder's own statement of how big the
         thing is, rather than our guess about what its name implies. */
      var d = distance({ lat: p.bbox[0], lng: p.bbox[1] }, { lat: p.bbox[2], lng: p.bbox[3] }) / 2;
      if (isFinite(d) && d > 0.5) return Math.min(d, 400);
    }
    return ({
      address: 3, street: 3, poi: 5, airport: 12, transport: 8,
      neighbourhood: 6, city: 30, postcode: 8, region: 120, country: 500
    })[p.kind] || fallback || 25;
  }

  /* Filter a list to what is near a point, annotate each with its
     distance, and — this is the part that matters — widen the circle
     rather than return nothing.

       o.radiusKm  starting radius (default: derived from the place)
       o.expand    rings to try before giving up
       o.min       keep widening until at least this many are found
       o.latKey / o.lngKey   field names on the items */
  function nearby(items, centre, o) {
    o = o || {};
    if (!centre || !isFinite(centre.lat) || !isFinite(centre.lng)) {
      return { items: [], radiusKm: 0, expanded: false, exact: false };
    }

    var latKey = o.latKey || 'lat';
    var lngKey = o.lngKey || 'lng';
    var min = o.min == null ? 1 : o.min;
    var base = o.radiusKm || radiusFor(centre, 25);
    var rings = o.expand || [base, base * 2.5, base * 6, base * 15, base * 40];

    var withDist = [];
    for (var i = 0; i < items.length; i++) {
      var it = items[i];
      var lat = Number(it[latKey]), lng = Number(it[lngKey]);
      if (!isFinite(lat) || !isFinite(lng)) continue;
      withDist.push({ item: it, km: distance(centre, { lat: lat, lng: lng }) });
    }
    withDist.sort(function (a, b) { return a.km - b.km; });

    for (var r = 0; r < rings.length; r++) {
      var radius = Math.min(rings[r], 20000);
      var hit = withDist.filter(function (x) { return x.km <= radius; });
      if (hit.length >= min || r === rings.length - 1) {
        return {
          items: hit.map(function (x) { x.item.distanceKm = Math.round(x.km * 10) / 10; return x.item; }),
          radiusKm: Math.round(radius),
          expanded: r > 0,
          exact: r === 0,
          /* Everything with coordinates, nearest first, for a caller
             that would rather show the closest five than nothing. */
          all: withDist.map(function (x) { x.item.distanceKm = Math.round(x.km * 10) / 10; return x.item; })
        };
      }
    }

    return { items: [], radiusKm: 0, expanded: false, exact: false, all: [] };
  }

  /* Does one record satisfy one search? Coordinates decide when both
     sides have them; text decides when they do not. Legacy listings
     that were saved before pinning existed still have to be findable,
     so the text path is a real path and not an apology. */
  function match(item, target, o) {
    o = o || {};
    if (!target) return true;

    var lat = Number(item[o.latKey || 'lat']);
    var lng = Number(item[o.lngKey || 'lng']);

    if (isFinite(lat) && isFinite(lng) && isFinite(target.lat)) {
      var km = distance(target, { lat: lat, lng: lng });
      if (km <= (o.radiusKm || radiusFor(target, 25))) return true;
      /* Outside the circle but the text still says the same city —
         a listing pinned to the wrong side of a big metro should not
         vanish from a search for that metro. */
      if (o.strict) return false;
    }

    var hay = norm([
      item.location, item.city, item.area, item.name, item.title, item.country
    ].filter(Boolean).join(' '));
    if (!hay) return false;

    var needles = [target.name, target.city, target.area].filter(Boolean).map(norm);
    for (var i = 0; i < needles.length; i++) {
      if (needles[i] && hay.indexOf(needles[i]) > -1) return true;
    }
    return false;
  }

  /* A record with no pin, only text. Resolve what we can offline so old
     inventory still plots on a map and still answers a radius search. */
  function parse(text) {
    var hits = searchSeed(text, 1);
    return hits.length ? hits[0] : null;
  }

