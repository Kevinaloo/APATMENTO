  function place(o) {
    var name = str(o.name);
    var label = str(o.label) || name;
    return {
      id: o.id || ('pt:' + o.lat + ',' + o.lng),
      name: name,
      label: label,
      short: str(o.short) || shortOf(o, label),
      lat: Number(o.lat),
      lng: Number(o.lng),
      kind: o.kind || 'place',
      street: str(o.street),
      area: str(o.area),
      city: str(o.city),
      state: str(o.state),
      country: str(o.country),
      countryCode: str(o.countryCode).toLowerCase(),
      postcode: str(o.postcode),
      bbox: Array.isArray(o.bbox) && o.bbox.length === 4 ? o.bbox : null,
      score: Number(o.score) || 0,
      distanceKm: typeof o.distanceKm === 'number' ? o.distanceKm : null,
      source: o.source || 'unknown'
    };
  }

  function str(v) { return String(v == null ? '' : v).replace(/\s+/g, ' ').trim(); }

  function shortOf(o, label) {
    var parts = [o.name, o.area || o.street, o.city, o.country].filter(uniqTruthy());
    return parts.slice(0, 3).join(', ') ||
           String(label).split(',').slice(0, 3).map(function (s) { return s.trim(); }).join(', ');
  }

