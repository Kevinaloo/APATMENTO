  /* Comparison form. Accents are stripped rather than respected on
     purpose: a guest types "medellin" and means Medellín, and a host
     types "Zurich" and means Zürich. Matching has to survive a keyboard
     that cannot produce the character the place is spelled with. */
  function norm(s) {
    var t = String(s == null ? '' : s).toLowerCase();
    if (t.normalize) t = t.normalize('NFD').replace(/[\u0300-\u036f]/g, '');
    return t.replace(/[^a-z0-9 ]+/g, ' ').replace(/\s+/g, ' ').trim();
  }

  var _seedIndex = null;

  function seedIndex() {
    if (_seedIndex) return _seedIndex;
    _seedIndex = SEED.map(function (row, i) {
      return {
        i: i,
        name: row[0],
        parent: row[1],
        country: row[2],
        cc: row[3],
        lat: row[4],
        lng: row[5],
        kind: row[6],
        n: norm(row[0]),
        hay: norm([row[0], row[1], row[2]].join(' '))
      };
    });
    return _seedIndex;
  }

  /* Instant, offline, zero-latency. Deliberately generous about what
     counts as a match — this is the layer that keeps the dropdown from
     ever being empty, and the network layer that follows it is the one
     that is precise. */
  function searchSeed(q, limit) {
    var query = norm(q);
    if (!query) return [];
    if (ALIASES[query]) query = norm(ALIASES[query]);

    var out = [];
    var idx = seedIndex();

    for (var i = 0; i < idx.length; i++) {
      var e = idx[i];
      var s = -1;
      if (e.n === query) s = 0;
      else if (e.n.indexOf(query) === 0) s = 1;
      else if (e.hay.indexOf(query) === 0) s = 2;
      else if (e.n.indexOf(query) > -1) s = 3;
      else if (e.hay.indexOf(query) > -1) s = 4;
      if (s < 0) continue;
      /* Cities outrank neighbourhoods at equal textual quality: someone
         typing three letters usually means the big thing. */
      var rank = s * 10 + (e.kind === 'city' ? 0 : e.kind === 'neighbourhood' ? 1 : 2);
      out.push({ e: e, r: rank });
    }

    out.sort(function (a, b) { return a.r - b.r; });

    return out.slice(0, limit || 6).map(function (o) {
      var e = o.e;
      return place({
        id: 'seed:' + e.i,
        name: e.name,
        label: [e.name, e.parent, e.country].filter(uniqTruthy()).join(', '),
        lat: e.lat,
        lng: e.lng,
        kind: e.kind,
        city: e.kind === 'city' ? e.name : e.parent,
        country: e.country,
        countryCode: e.cc,
        source: 'cabana'
      });
    });
  }

  /* Small helper for the join above: drops empties *and* repeats, so
     "Nairobi, Nairobi, Kenya" never reaches a human. */
  function uniqTruthy() {
    var seen = {};
    return function (v) {
      if (!v) return false;
      var k = String(v).toLowerCase();
      if (seen[k]) return false;
      seen[k] = 1;
      return true;
    };
  }

