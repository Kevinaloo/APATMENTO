  var mem = {};

  function ssGet(k) {
    try { var raw = sessionStorage.getItem(k); return raw ? JSON.parse(raw) : null; }
    catch (e) { return null; }
  }
  function ssSet(k, v) { try { sessionStorage.setItem(k, JSON.stringify(v)); } catch (e) {} }
  function lsGet(k) {
    try { var raw = localStorage.getItem(k); return raw ? JSON.parse(raw) : null; }
    catch (e) { return null; }
  }
  function lsSet(k, v) { try { localStorage.setItem(k, JSON.stringify(v)); } catch (e) {} }

  /* Where to weight results toward. Set by the last place the user
     picked, or by their device fix — never by an IP guess, which is
     wrong often enough to be infuriating when it is. */
  function getBias() {
    var b = lsGet(BIAS_KEY);
    return b && isFinite(b.lat) && isFinite(b.lng) ? b : null;
  }

  function setBias(p) {
    if (!p || !isFinite(p.lat) || !isFinite(p.lng)) return;
    lsSet(BIAS_KEY, { lat: p.lat, lng: p.lng, label: p.short || p.label || '', at: Date.now() });
  }

  function recents() {
    var r = lsGet(RECENT_KEY);
    return Array.isArray(r) ? r.filter(function (p) { return p && isFinite(p.lat); }) : [];
  }

  function remember(p) {
    if (!p || !isFinite(p.lat)) return;
    var list = recents().filter(function (x) {
      return !(Math.abs(x.lat - p.lat) < 1e-5 && Math.abs(x.lng - p.lng) < 1e-5);
    });
    list.unshift(p);
    lsSet(RECENT_KEY, list.slice(0, RECENT_MAX));
    setBias(p);
  }

  /* ════════════════════════════════════════════════════════════════
     4 · SEARCH
     ════════════════════════════════════════════════════════════════ */

  var apiAlive = true;   // flips false after a hard failure, so we stop knocking
  var inflight = {};     // query key → promise, so ten keystrokes are one call

  /* Forward search.

       o.limit    how many (default 8)
       o.near     {lat,lng} to bias toward; defaults to the stored bias
       o.country  ISO2 or array, when a form is genuinely single-country
       o.lang     response language (default the document's)
       o.seed     merge instant gazetteer hits (default true)
       o.signal   AbortSignal

     Resolves to [] rather than rejecting. A search box is not the place
     to surface a network error as an exception. */
  function search(q, o) {
    o = o || {};
    q = str(q);
    if (q.length < MIN_CHARS) return Promise.resolve([]);

    var limit = o.limit || 8;
    var near = o.near || (o.bias === false ? null : getBias());
    var country = o.country
      ? (Array.isArray(o.country) ? o.country : String(o.country).split(','))
          .map(function (c) { return str(c).toLowerCase(); }).filter(function (c) { return c.length === 2; })
      : null;

    var key = 'g:' + q.toLowerCase() + '|' + limit + '|' + (country ? country.join('+') : '*') +
              '|' + (near ? near.lat.toFixed(1) + ',' + near.lng.toFixed(1) : '-');

    var local = o.seed === false ? [] : searchSeed(q, Math.min(limit, 5));

    if (mem[key]) return Promise.resolve(merge(local, mem[key], limit));
    var stored = ssGet(key);
    if (stored) { mem[key] = stored; return Promise.resolve(merge(local, stored, limit)); }
    if (inflight[key]) return inflight[key].then(function (r) { return merge(local, r, limit); });

    var run = remote(q, { limit: limit, near: near, country: country, lang: o.lang, signal: o.signal })
      .then(function (rows) {
        if (rows.length) { mem[key] = rows; ssSet(key, rows); }
        return rows;
      })
      .catch(function () { return []; })
      .then(function (rows) { delete inflight[key]; return rows; });

    inflight[key] = run;
    return run.then(function (rows) { return merge(local, rows, limit); });
  }

  /* Gazetteer hits lead — they are Cabana's own inventory areas and a
     guest searching them should land on the canonical record, not on
     whichever OSM node happens to share the name. Remote results fill
     the rest and are deduped against what is already shown. */
  function merge(local, remoteRows, limit) {
    var out = [];
    var seen = {};

    function push(p) {
      if (!p || !isFinite(p.lat) || !isFinite(p.lng)) return;
      var k = norm(p.name) + '|' + p.lat.toFixed(2) + '|' + p.lng.toFixed(2);
      if (seen[k]) return;
      seen[k] = 1;
      out.push(p);
    }

    local.forEach(push);
    (remoteRows || []).forEach(push);
    return out.slice(0, limit);
  }

  function remote(q, o) {
    if (!apiAlive) return direct(q, o);

    var u = API + '?q=' + encodeURIComponent(q) + '&limit=' + (o.limit || 8) +
            '&lang=' + encodeURIComponent(o.lang || docLang());
    if (o.near) u += '&near=' + o.near.lat.toFixed(4) + ',' + o.near.lng.toFixed(4);
    if (o.country && o.country.length) u += '&country=' + o.country.join(',');

    return fetch(u, { signal: o.signal })
      .then(function (r) {
        /* A 404 means this deploy has no geocode route at all — stop
           asking for the rest of the session and use the open providers
           straight away, rather than paying a failed round trip per
           keystroke forever. */
        if (r.status === 404) { apiAlive = false; throw new Error('no route'); }
        if (!r.ok) throw new Error('geocode ' + r.status);
        return r.json();
      })
      .then(function (data) { return (data.results || []).map(place); })
      .catch(function (e) {
        if (e && e.name === 'AbortError') throw e;
        return direct(q, o);
      });
  }

  /* Last resort: talk to the open providers from the browser. */
  function direct(q, o) {
    var u = PHOTON + '?q=' + encodeURIComponent(q) + '&limit=' + (o.limit || 8) + '&lang=en';
    if (o.near) u += '&lat=' + o.near.lat.toFixed(4) + '&lon=' + o.near.lng.toFixed(4);

    return fetch(u, { signal: o.signal })
      .then(function (r) { return r.ok ? r.json() : { features: [] }; })
      .then(function (d) {
        var rows = (d.features || []).map(fromPhoton).filter(Boolean);
        if (rows.length) return rows;
        return directOSM(q, o);
      })
      .catch(function (e) {
        if (e && e.name === 'AbortError') throw e;
        return directOSM(q, o);
      });
  }

  function directOSM(q, o) {
    var u = NOMINATIM + '?format=jsonv2&addressdetails=1&limit=' + (o.limit || 8) +
            '&q=' + encodeURIComponent(q);
    return fetch(u, { signal: o.signal, headers: { 'Accept-Language': 'en' } })
      .then(function (r) { return r.ok ? r.json() : []; })
      .then(function (rows) { return (rows || []).map(fromOSM).filter(Boolean); })
      .catch(function () { return []; });
  }

  function fromPhoton(f) {
    var p = f.properties || {}, g = f.geometry || {};
    var lng = Number(g.coordinates && g.coordinates[0]);
    var lat = Number(g.coordinates && g.coordinates[1]);
    if (!isFinite(lat) || !isFinite(lng)) return null;
    var name = str(p.name) || str(p.street) || str(p.city) || str(p.country);
    return place({
      id: 'photon:' + (p.osm_id || lat + ',' + lng),
      name: name,
      label: [p.housenumber ? p.housenumber + ' ' + (p.street || '') : p.street,
              name, p.district, p.city, p.state, p.country].filter(uniqTruthy()).join(', '),
      lat: lat, lng: lng,
      kind: kindOf(p.osm_value, p.osm_key),
      street: p.street, area: p.district, city: p.city || p.county,
      state: p.state, country: p.country, countryCode: p.countrycode,
      postcode: p.postcode, source: 'photon'
    });
  }

  function fromOSM(r) {
    var lat = Number(r.lat), lng = Number(r.lon);
    if (!isFinite(lat) || !isFinite(lng)) return null;
    var a = r.address || {};
    var street = a.road || a.pedestrian || '';
    return place({
      id: 'osm:' + (r.osm_id || lat + ',' + lng),
      name: str(r.name) || street || a.suburb || a.city || String(r.display_name || '').split(',')[0],
      label: r.display_name,
      lat: lat, lng: lng,
      kind: kindOf(r.type, r.class),
      street: street, area: a.suburb || a.neighbourhood,
      city: a.city || a.town || a.village || a.county,
      state: a.state, country: a.country, countryCode: a.country_code,
      postcode: a.postcode, source: 'nominatim'
    });
  }

